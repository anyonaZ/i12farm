// Turns a national list of sub-counties and wards into SQL for the reference
// tables. Uses only Node built-ins.
//
//   node scripts/import-admin-units.mjs wards.csv > db/migrations/<timestamp>_admin_units.sql
//
// Expected CSV header (any order, case-insensitive):
//   county_code, sub_county, ward_code, ward
// Source: the IEBC list of county assembly wards (one row per ward). Sub-county
// here means the constituency, as IEBC publishes it.
import { readFileSync } from 'node:fs';

const file = process.argv[2];
if (!file) {
  console.error('usage: node scripts/import-admin-units.mjs <wards.csv>');
  process.exit(1);
}

function parseCsv(text) {
  const rows = [];
  let row = [], cell = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (ch === '"') quoted = false;
      else cell += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { row.push(cell); cell = ''; }
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i++;
      row.push(cell); cell = '';
      if (row.some((c) => c.trim() !== '')) rows.push(row);
      row = [];
    } else cell += ch;
  }
  row.push(cell);
  if (row.some((c) => c.trim() !== '')) rows.push(row);
  return rows;
}

const titleCase = (s) => s.trim().toLowerCase().replace(/\s+/g, ' ').replace(/(^|[\s'/-])\p{L}/gu, (m) => m.toUpperCase());
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const [header, ...data] = parseCsv(readFileSync(file, 'utf8'));
const col = Object.fromEntries(header.map((h, i) => [h.trim().toLowerCase(), i]));
for (const need of ['county_code', 'sub_county', 'ward']) {
  if (!(need in col)) {
    console.error(`missing column: ${need}`);
    process.exit(1);
  }
}

const subCounties = new Map();
const wards = [];
for (const r of data) {
  const county = Number.parseInt(r[col.county_code], 10);
  if (!(county >= 1 && county <= 47)) continue;
  const sub = titleCase(r[col.sub_county]);
  const ward = titleCase(r[col.ward]);
  const code = 'ward_code' in col ? r[col.ward_code].trim() : '';
  subCounties.set(`${county}|${sub}`, { county, sub });
  wards.push({ county, sub, ward, code });
}

console.log('-- Generated by scripts/import-admin-units.mjs from', file);
console.log('begin;');
console.log('insert into public.sub_counties (county_code, name) values');
console.log([...subCounties.values()].map((s) => `  (${s.county}, ${q(s.sub)})`).join(',\n'));
console.log('on conflict (county_code, name) do nothing;');
console.log('insert into public.wards (iebc_code, sub_county_id, county_code, name)');
console.log('select v.code, sc.id, v.county, v.ward from (values');
console.log(wards.map((w) => `  (${w.code ? q(w.code) : 'null'}, ${w.county}::smallint, ${q(w.sub)}, ${q(w.ward)})`).join(',\n'));
console.log(') as v(code, county, sub, ward)');
console.log('join public.sub_counties sc on sc.county_code = v.county and sc.name = v.sub');
console.log('on conflict (sub_county_id, name) do nothing;');
console.log('commit;');
console.error(`${subCounties.size} sub-counties, ${wards.length} wards`);
